//! Module 11 — Iterators, exercises for lessons 1–6.

use crate::content::types::{ExerciseKind, SeedExercise};

pub fn exercises() -> Vec<SeedExercise> {
    vec![
        // L1 The Manual Loop
        SeedExercise::new(
            Some(0),
            ExerciseKind::Mcq,
            "What is the real problem with the hand-written index loop that filters into a `Vec`?",
            &[
                "It is slower than a `for` loop",
                "Most of it is bookkeeping — the index, the bounds, the `push` — not the intent",
                "It cannot handle large lists",
            ],
            1,
            "The loop works, but the intent — 'keep the errors and take their messages' — is buried in \
             index and `push` bookkeeping. Iterators name the operations: iterate, filter, map.",
        ),

        // L2 What an Iterator Is
        SeedExercise::new(
            Some(1),
            ExerciseKind::PredictOutput,
            "`next` is called on an iterator with one item. Predict both outputs.",
            &["Some(5) None", "5 0", "Some(5) Some(5)"],
            0,
            "The first `next` yields `Some(5)`; the second finds it exhausted and returns `None`. `next` \
             returns `Option` precisely because a stream can end.",
        )
        .with_code(
            "fn main() {\n    let mut it = vec![5].into_iter();\n    println!(\"{:?} {:?}\", it.next(), it.next());\n}",
        ),

        // L3 Three Ways to Iterate
        SeedExercise::new(
            Some(2),
            ExerciseKind::FillGap,
            "Fill the gap with the method that lets the loop change each element in place.",
            &["iter_mut", "iter", "into_iter"],
            0,
            "`iter_mut()` yields `&mut T`, so the body may change each element while the collection stays \
             yours. `iter()` is read-only; `into_iter()` consumes the collection.",
        )
        .with_code("for entry in entries.____() {\n    entry.visited = true;\n}"),

        // L4 The for Loop Desugared
        SeedExercise::new(
            Some(3),
            ExerciseKind::Mcq,
            "What does a `for` loop actually do under the hood?",
            &[
                "It uses index arithmetic generated by the compiler",
                "It calls `into_iter` and then `next` until it gets `None`",
                "It is special syntax with no trait behind it",
            ],
            1,
            "`for x in y` uses `IntoIterator` to get an iterator, then calls `next` until `None`. It is \
             built on the same trait as every chain you have written.",
        ),

        // L5 Adapters versus Consumers
        SeedExercise::new(
            Some(4),
            ExerciseKind::Mcq,
            "Which of these is a consumer?",
            &["`map`", "`filter`", "`collect`"],
            2,
            "`collect` produces a value and runs the pipeline. `map` and `filter` are adapters — they \
             return another iterator and do no work yet.",
        ),

        // L6 Ranges and Sources
        SeedExercise::new(
            Some(5),
            ExerciseKind::PredictOutput,
            "Predict what this prints.",
            &["0 1 2", "1 2 3", "0 1 2 3"],
            0,
            "`0..3` is a range iterator yielding `0, 1, 2` — the end is exclusive. Ranges are ordinary \
             iterators, so they chain with every adapter.",
        )
        .with_code("fn main() {\n    for n in 0..3 {\n        print!(\"{n} \");\n    }\n}"),
    ]
}
